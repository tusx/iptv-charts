"""Logical backup and restore.

A raw copy of catalog.db would be mostly the provider catalog: hundreds of
megabytes that can be regenerated by a sync. The backup therefore contains
only the app's own state (sources, settings, library, queue, history) as JSON
inside a ZIP. Restore replaces those tables and requires a sync afterwards,
which is what "full restore without the VOD list" means in practice.
"""

from __future__ import annotations

import io
import json
import logging
import time
import zipfile
from typing import Any

from . import config, db, downloader, naming, scheduler, sync

logger = logging.getLogger("iptv_charts.backup")

FORMAT = "iptv-charts-backup"
FORMAT_VERSION = 1
MAX_ZIP_BYTES = 64 * 1024 * 1024
MAX_UNCOMPRESSED = 256 * 1024 * 1024
MAX_ROWS = 500_000

#: Insert order matters because of foreign keys.
TABLES = (
    "sources",
    "quality_profiles",
    "movies",
    "series",
    "series_episodes",
    "downloads",
    "settings",
    "history",
    "scan_results",
    "task_state",
)
EXCLUDED = (
    "items", "categories", "items_fts", "metadata_cache",
    "provider_series_cache", "stream_probes", "image cache",
)

TEMPLATE_TOKENS = {
    "movie_folder_template": naming.MOVIE_FOLDER_TOKENS,
    "movie_file_template": naming.MOVIE_FILE_TOKENS,
    "series_folder_template": naming.SERIES_FOLDER_TOKENS,
    "season_folder_template": naming.SEASON_FOLDER_TOKENS,
    "episode_file_template": naming.EPISODE_FILE_TOKENS,
}


class RestoreBusy(RuntimeError):
    """The app is doing something that must finish before a restore."""


def _rows(conn, table: str) -> list[dict]:
    return [dict(row) for row in conn.execute(f"SELECT * FROM {table}")]


def export_zip(conn) -> bytes:
    counts = {table: db.get_one(conn, f"SELECT COUNT(*) AS n FROM {table}")["n"]
              for table in TABLES}
    manifest = {
        "format": FORMAT,
        "format_version": FORMAT_VERSION,
        "schema_version": db.SCHEMA_VERSION,
        "app_version": __import__("iptv_charts").__version__,
        "created_at": int(time.time()),
        "tables": counts,
        "excluded": list(EXCLUDED),
        "contains_secrets": True,
        "note": ("This backup contains provider credentials and metadata tokens "
                 "in plain text. Keep it private."),
    }
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("manifest.json", json.dumps(manifest, indent=2))
        for table in TABLES:
            archive.writestr(
                f"tables/{table}.json",
                json.dumps(_rows(conn, table), ensure_ascii=False),
            )
    return buffer.getvalue()


def _read_archive(data: bytes) -> tuple[dict, dict[str, list[dict]]]:
    if not data:
        raise ValueError("The backup file is empty.")
    if len(data) > MAX_ZIP_BYTES:
        raise ValueError("The backup file is too large.")
    try:
        archive = zipfile.ZipFile(io.BytesIO(data))
    except zipfile.BadZipFile as exc:
        raise ValueError("That is not a valid ZIP backup.") from exc

    tables: dict[str, list[dict]] = {}
    with archive:
        names = set(archive.namelist())
        if "manifest.json" not in names:
            raise ValueError("The ZIP has no manifest; it is not an IPTV Charts backup.")
        try:
            manifest = json.loads(archive.read("manifest.json"))
        except (ValueError, KeyError) as exc:
            raise ValueError("The backup manifest is unreadable.") from exc
        if not isinstance(manifest, dict) or manifest.get("format") != FORMAT:
            raise ValueError("That ZIP is not an IPTV Charts backup.")
        if int(manifest.get("format_version") or 0) != FORMAT_VERSION:
            raise ValueError("This backup was made by an incompatible version of the app.")
        if int(manifest.get("schema_version") or 0) > db.SCHEMA_VERSION:
            raise ValueError("This backup comes from a newer version of the app.")

        expected = {f"tables/{table}.json" for table in TABLES}
        unknown = names - expected - {"manifest.json"}
        if unknown:
            raise ValueError(f"The backup contains unexpected files: {', '.join(sorted(unknown)[:3])}.")
        total_size = 0
        total_rows = 0
        for table in TABLES:
            entry = f"tables/{table}.json"
            if entry not in names:
                raise ValueError(f"The backup is missing {entry}.")
            info = archive.getinfo(entry)
            total_size += info.file_size
            if total_size > MAX_UNCOMPRESSED:
                raise ValueError("The backup expands to more data than allowed.")
            try:
                rows = json.loads(archive.read(entry))
            except (ValueError, KeyError) as exc:
                raise ValueError(f"The backup's {table} table is unreadable.") from exc
            if not isinstance(rows, list) or not all(isinstance(row, dict) for row in rows):
                raise ValueError(f"The backup's {table} table has the wrong shape.")
            total_rows += len(rows)
            if total_rows > MAX_ROWS:
                raise ValueError("The backup contains too many rows.")
            counts = manifest.get("tables")
            if isinstance(counts, dict) and int(counts.get(table, len(rows))) != len(rows):
                raise ValueError(f"The backup's {table} row count does not match its manifest.")
            tables[table] = rows
    return manifest, tables


def _table_columns(conn, table: str) -> list[str]:
    return [row["name"] for row in conn.execute(f"PRAGMA table_info({table})")]


def _insert_rows(conn, table: str, rows: list[dict]) -> int:
    if not rows:
        return 0
    columns = _table_columns(conn, table)
    inserted = 0
    for row in rows:
        values = {key: row[key] for key in columns if key in row}
        if not values:
            continue
        names = list(values)
        placeholders = ", ".join("?" for _ in names)
        conn.execute(
            f"INSERT INTO {table} ({', '.join(names)}) VALUES ({placeholders})",
            [values[name] for name in names],
        )
        inserted += 1
    return inserted


def _confined_media_path(value: Any) -> str | None:
    if not value:
        return None
    try:
        naming.confine(str(value), config.media_dir())
        return str(value)
    except naming.TemplateError:
        return None


def _prepare_rows(tables: dict[str, list[dict]]) -> None:
    for row in tables["sources"]:
        row["sync_status"] = "idle"
        row["sync_message"] = "Restored; run a sync to rebuild the catalog."
    for row in tables["movies"]:
        path = _confined_media_path(row.get("file_path"))
        row["file_path"] = path
        if not path:
            row["file_size"] = None
            row["resolution"] = None
            row["imported_at"] = None
    for row in tables["series_episodes"]:
        path = _confined_media_path(row.get("file_path"))
        row["file_path"] = path
        if not path:
            row["file_size"] = None
            row["resolution"] = None
            row["imported_at"] = None
    for row in tables["downloads"]:
        if row.get("status") in downloader.ACTIVE:
            row["status"] = "queued"
            row["temp_path"] = None
            row["next_attempt_at"] = None
            row["started_at"] = None
            row["finished_at"] = None
            row["error"] = None
    settings = {row.get("key"): row.get("value") for row in tables["settings"]}
    for key, allowed in TEMPLATE_TOKENS.items():
        if key in settings:
            naming.validate_template(settings[key] or "", allowed)
    if "metadata_language" not in settings:
        tables["settings"].append({"key": "metadata_language", "value": "en-US"})


def restore(conn, data: bytes) -> dict:
    """Replace the app's own tables from a backup and queue catalog syncs."""
    manifest, tables = _read_archive(data)
    if sync.is_busy():
        raise RestoreBusy("A playlist sync is running. Wait for it to finish first.")
    if scheduler.is_running():
        raise RestoreBusy("A library task is running. Wait for it to finish first.")
    active = db.get_one(
        conn,
        "SELECT COUNT(*) AS n FROM downloads WHERE status IN (?, ?, ?)",
        downloader.ACTIVE,
    )
    if active and active["n"]:
        raise RestoreBusy("There are active downloads. Wait for them to finish first.")
    _prepare_rows(tables)

    counts: dict[str, int] = {}
    try:
        conn.execute("BEGIN IMMEDIATE")
        # A probe result is only meaningful for the provider identity it came
        # from. The catalog is re-synced after a restore, so discard probes
        # rather than letting a stale resolution/audio decision survive.
        conn.execute("DELETE FROM stream_probes")
        for table in ("scan_results", "history", "downloads", "series_episodes",
                      "movies", "series", "quality_profiles", "task_state",
                      "settings", "sources"):
            conn.execute(f"DELETE FROM {table}")
        for table in TABLES:
            counts[table] = _insert_rows(conn, table, tables[table])
        conn.commit()
    except Exception:
        conn.rollback()
        raise

    source_ids = [int(row["id"]) for row in tables["sources"] if row.get("id") is not None]
    queued = sync.enqueue(source_ids) if source_ids else []
    logger.info("backup: restored %s (sync queued: %s)",
                {key: value for key, value in counts.items() if value}, queued)
    return {
        "counts": counts,
        "sources": source_ids,
        "sync_queued": queued,
        "needs_sync": bool(source_ids),
        "created_at": manifest.get("created_at"),
    }


